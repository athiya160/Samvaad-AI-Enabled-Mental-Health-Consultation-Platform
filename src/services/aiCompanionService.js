  // Section 7 Check: Refusal of clinical diagnosis, medication, or formal therapy plans
  checkAdviceRedirection(text, language = 'en') {
    if (!text) return null;
    const asksClinical = CLINICAL_DIAGNOSIS_OR_PRESCRIPTION_PATTERNS.some(p => p.test(text));
    if (asksClinical) {
      return {
        text: PRESCRIBED_REDIRECT_STATEMENT[language] || PRESCRIBED_REDIRECT_STATEMENT.en,
        isCrisis: false,
        isAdviceRedirect: true,
        detectedDomains: Array.from(this.detectedDomains)
      };
    }
    return null;
  }

  // Primary conversation method: instant safety, backend LLM integration, and empathetic reflection
  async generateResponse(userMessage, conversationHistory = [], language = 'en') {
    // 1. Zero-latency client-side crisis check (Section 13 & 14)
    const clientCrisis = this.checkClientSafety(userMessage, language);
    if (clientCrisis) {
      return clientCrisis;
    }

    // 2. Section 7 Clinical prescription/diagnosis check
    const adviceRedirect = this.checkAdviceRedirection(userMessage, language);
    if (adviceRedirect) {
      return adviceRedirect;
    }

    // 3. Try backend API (/api/chat) for secure LLM response
    try {
      const res = await fetch('/api/chat', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          message: userMessage,
          history: conversationHistory.map(m => ({
            role: m.sender === 'user' ? 'user' : 'model',
            parts: [{ text: m.text }]
          })),
          language
        })
      });

      if (res.ok) {
        const data = await res.json();
        if (data.ok && data.text) {
          return {
            text: data.text,
            isCrisis: Boolean(data.isCrisis),
            isPhysicalEmergency: Boolean(data.isPhysicalEmergency),
            provider: data.provider || 'gemini',
            detectedDomains: data.detectedDomains || Array.from(this.detectedDomains)
          };
        }
      }
    } catch (err) {
      // Backend not running or fetch failed, proceed to intelligent local generator
    }

    // 4. Empathetic conversational reflection engine (conversational fallback)
    return this.generateFallbackChatResponse(userMessage, conversationHistory, language);
  }

